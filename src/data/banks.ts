/**
 * Detect bank details from first 6 digits
 */
export function detectBank(cardNumber: string): BankInfo {
  const clean = cardNumber.replace(/\D/g, '');
  if (clean.length < 6) return DEFAULT_BANK;
  const prefix = clean.substring(0, 6);
  return IRAN_BANKS[prefix] || DEFAULT_BANK;
}

/**
 * Formats 16-digit card number with dashes or spaces: 6037-9912-3456-7890
 */
export function formatCardNumber(num: string): string {
  const clean = num.replace(/\D/g, '').substring(0, 16);
  const parts = [];
  for (let i = 0; i < clean.length; i += 4) {
    parts.push(clean.substring(i, i + 4));
  }
  return parts.join(' - ');
}

/**
 * Validates 16 digit card number using Luhn algorithm
 */
export function isValidCardNumber(num: string): boolean {
  const clean = num.replace(/\D/g, '');
  if (clean.length !== 16) return false;
  let sum = 0;
  for (let i = 0; i < 16; i++) {
    let digit = parseInt(clean[i], 10);
    if (i % 2 === 0) {
      digit *= 2;
      if (digit > 9) digit -= 9;
    }
    sum += digit;
  }
  return sum % 10 === 0;
}

/**
 * Calculate official Shetab fee based on transaction amount (in Toman)
 */
export function calculateShetabFee(amountInToman: number): number {
  if (amountInToman <= 0) return 0;
  if (amountInToman <= 1_000_000) return 720; // 7,200 Rials
  if (amountInToman <= 2_000_000) return 1_000;
  if (amountInToman <= 3_000_000) return 1_280;
  if (amountInToman <= 5_000_000) return 1_600;
  if (amountInToman <= 10_000_000) return 2_400;
  return 3_500; // Above 10M Toman
}

/**
 * Convert number to Persian verbal text (e.g., 1500000 -> یک میلیون و پانصد هزار تومان تمام)
 */
export function numberToPersianWords(num: number): string {
  if (!num || isNaN(num) || num <= 0) return 'صفر تومان';

  const units = ['', 'یک', 'دو', 'سه', 'چهار', 'پنج', 'شش', 'هفت', 'هشت', 'نه'];
  const teens = ['ده', 'یازده', 'دوازده', 'سیزده', 'چهارده', 'پانزده', 'شانزده', 'هفده', 'هجده', 'نوزده'];
  const tens = ['', '', 'بیست', 'سی', 'چهل', 'پنجاه', 'شصت', 'هفتاد', 'هشتاد', 'نود'];
  const hundreds = ['', 'یکصد', 'دویست', 'سیصد', 'چهارصد', 'پانصد', 'ششصد', 'هفتصد', 'هشتصد', 'نهصد'];
  const scales = ['', 'هزار', 'میلیون', 'میلیارد', 'تریلیون'];

  function convertChunk(n: number): string {
    const parts: string[] = [];
    const h = Math.floor(n / 100);
    const remainder = n % 100;
    if (h > 0) parts.push(hundreds[h]);

    if (remainder >= 10 && remainder < 20) {
      parts.push(teens[remainder - 10]);
    } else {
      const t = Math.floor(remainder / 10);
      const u = remainder % 10;
      if (t > 0) parts.push(tens[t]);
      if (u > 0) parts.push(units[u]);
    }
    return parts.join(' و ');
  }

  const chunks: string[] = [];
  let temp = num;
  let scaleIndex = 0;

  while (temp > 0) {
    const chunk = temp % 1000;
    if (chunk > 0) {
      const chunkStr = convertChunk(chunk);
      const scaleStr = scales[scaleIndex];
      chunks.unshift(scaleStr ? `${chunkStr} ${scaleStr}` : chunkStr);
    }
    temp = Math.floor(temp / 1000);
    scaleIndex++;
  }

  return chunks.join(' و ') + ' تومان تمام';
}

/**
 * Formats number with commas: 1250000 -> 1,250,000
 */
export function formatAmount(num: number | string): string {
  if (!num) return '0';
  const clean = num.toString().replace(/\D/g, '');
  return clean.replace(/\B(?=(\d{3})+(?!\d))/g, ',');
}
